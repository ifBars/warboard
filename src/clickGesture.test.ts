import { expect, test } from "bun:test";
import { createClickGesture } from "./clickGesture";
test("terrain clicks tolerate jitter but reject orbit, pan, cancellation and multitouch", () => {
  const g = createClickGesture();
  g.down(1, 10, 10, 0);
  g.up(1, 12, 12);
  expect(g.allowsClick()).toBe(true);
  g.down(1, 10, 10, 0);
  g.move(1, 60, 10);
  g.up(1, 10, 10);
  expect(g.allowsClick()).toBe(false);
  g.down(1, 10, 10, 0);
  g.up(1, 30, 10);
  expect(g.allowsClick()).toBe(false);
  g.down(1, 10, 10, 2);
  g.up(1, 10, 10);
  expect(g.allowsClick()).toBe(false);
  g.down(1, 10, 10, 0);
  g.cancel(1);
  expect(g.allowsClick()).toBe(false);
  g.down(1, 10, 10, 0);
  g.down(2, 20, 20, 0);
  g.up(1, 10, 10);
  g.up(2, 20, 20);
  expect(g.allowsClick()).toBe(false);
  g.down(1, 10, 10, 0);
  g.up(1, 10, 10);
  expect(g.allowsClick()).toBe(true);
});
